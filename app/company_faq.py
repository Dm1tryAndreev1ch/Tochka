# Прямые просьбы записать/перезвонить обрабатывает обычный диалог (extract_common и LLM),
# а не справочник. Вопросы вида «как записаться?» сюда не относятся.
ACTION_REQUEST = re.compile(
    r"\b(?:запиши\w*|оформи\w*|запишите\s+меня|хочу\s+записаться|хотел\w*\s+бы\s+записаться|"
    r"давай\w*\s+запис\w*|перезвони\w*|соедини\w*|переведи\w*|позови\w*)\b"
)
DATA_PAYLOAD = re.compile(
    r"\+?\d[\d\s()-]{7,}|\b\d{1,2}[:.]\d{2}\b|\bменя\s+зовут\b|"
    r"\b(?:мо[йе]|мо[её])\s+(?:имя|телефон|номер)\s*(?:[-—:]|это|равен)?\s*(?!неправильно|неверно)\w+\s*$"
)
SKIP_WORDS = 30


def normalize(text):
    value = text.lower().replace("ё", "е")
    value = re.sub(r"[^\w\s+-]", " ", value)
    return " ".join(value.split())


def company_topic(text):
    """Вернуть ключ темы для справочного вопроса либо None.

    Прямые просьбы («запишите меня…»), реплики с телефоном/временем и очень
    длинные тексты не считаются справочными вопросами и идут обычным путём.
    """
    value = normalize(text)
    if not value or len(value.split()) > SKIP_WORDS:
        return None
    if ACTION_REQUEST.search(value) or DATA_PAYLOAD.search(text.lower()):
        return None
    for topic, patterns in COMPILED:
        if any(pattern.search(value) for pattern in patterns):
            return topic
    return None


def company_reply(text, *, allowed_actions=None):
    """Готовый ответ о Точке или None, если вопрос не из справочника."""
    topic = company_topic(text)
    if topic is None:
        return None
    answer = ANSWERS[topic]
    if "booking" not in set(allowed_actions if allowed_actions is not None else {"booking"}):
        if topic == "beta_how":
            return None
    answer = answer.replace("{beta_conditions}", _beta_conditions()).replace("{notification}", _notification_sentence())
    return {"text": answer, "response_source": SOURCE}
